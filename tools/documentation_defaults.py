"""Generate published defaults from the firmware and server configuration."""
import argparse
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "robot_server"))

from backend.models import default_settings
from backend.state import HEARTBEAT_TTL, POSE_TTL, DIAGNOSTIC_RUN_SECONDS


def read_firmware():
    compiler = shutil.which("clang++") or shutil.which("g++")
    if compiler is None:
        raise RuntimeError("A host C++ compiler is required (clang++ or g++)")
    program = r'''
        #include <iostream>
        #include "config.h"
        int main() {
            std::cout << std::boolalpha
                << "{\"version\":\"" << config::firmware << "\""
                << ",\"closed_loop\":" << config::motorClosedLoop
                << ",\"max_v\":" << config::maxV
                << ",\"max_omega\":" << config::maxOmega
                << ",\"counts\":[" << config::pulsesPerTurn[0] << "," << config::pulsesPerTurn[1] << "]"
                << ",\"channels\":[" << config::wheelChannels[0] << "," << config::wheelChannels[1] << "]"
                << ",\"feed_forward\":" << config::feedForward
                << ",\"kp\":" << config::kp << ",\"ki\":" << config::ki
                << ",\"wheel_diameter\":" << config::wheelDiameter
                << ",\"track_width\":" << config::trackWidth
                << ",\"control_ms\":" << config::controlMs
                << ",\"telemetry_ms\":" << config::telemetryMs << "}";
        }
    '''
    with tempfile.TemporaryDirectory(prefix="acfield-defaults-") as folder:
        binary = Path(folder) / "config"
        subprocess.run([compiler, "-std=c++11", "-Wall", "-Wextra", "-Werror",
                        "-I", str(ROOT / "esp32_software/firmware/include"),
                        "-x", "c++", "-", "-o", str(binary)],
                       input=program, text=True, check=True)
        return json.loads(subprocess.check_output([str(binary)], text=True))


def render_defaults(firmware, english):
    robot = default_settings().robots[0]
    mode = ("Encoder wheel-speed loop" if english else "编码器轮速闭环") if firmware["closed_loop"] else "Open-loop PWM"
    rows = [
        ("Firmware" if english else "普通固件", firmware["version"]),
        ("Control mode" if english else "控制模式", mode),
        ("Feed-forward / PI", f"feedForward={firmware['feed_forward']}, kp={firmware['kp']}, ki={firmware['ki']}"),
        ("Encoder counts per output turn (left/right)" if english else "输出轴每圈计数（左/右）", "/".join(map(str, firmware["counts"]))),
        ("Logical left/right channels" if english else "逻辑左/右轮通道", "wheelChannels={" + ",".join(map(str, firmware["channels"])) + "}"),
        ("Wheel diameter / track" if english else "轮径 / 轮距", f"{firmware['wheel_diameter']:.3f} / {firmware['track_width']:.3f} m"),
        ("Device velocity limits" if english else "固件速度上限", f"{firmware['max_v']:.2f} m/s, {firmware['max_omega']:.2f} rad/s"),
        ("New server robot limits" if english else "主控新建车辆限速", f"{robot.max_v:.2f} m/s, {robot.max_omega:.2f} rad/s"),
        ("Motion / telemetry period" if english else "运动 / 遥测周期", f"{firmware['control_ms']} / {firmware['telemetry_ms']} ms"),
        ("Pose / heartbeat expiry" if english else "定位 / 心跳期限", f"{POSE_TTL * 1000:g} ms / {HEARTBEAT_TTL:g} s"),
        ("Diagnostic run limit" if english else "持续诊断上限", f"{DIAGNOSTIC_RUN_SECONDS:g} s"),
    ]
    header = "Parameter | Repository default" if english else "参数 | 仓库默认值"
    return "<!-- Generated by tools/documentation_defaults.py -->\n\n| " + header + " |\n| --- | --- |\n" + "".join(
        f"| {label} | `{value}` |\n" for label, value in rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    firmware = read_firmware()
    for locale in ("zh", "en"):
        path = ROOT / f"docs/.vitepress/generated/defaults.{locale}.md"
        expected = render_defaults(firmware, locale == "en")
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"Outdated {path.relative_to(ROOT)}; run tools/documentation_defaults.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
    print("Published defaults match firmware and server configuration")


if __name__ == "__main__":
    main()
